/**
 * 주어진 날짜(YYYY-MM-DD)의 공휴일 명칭 반환 (없으면 null)
 */
export function getHoliday(dateStr) {
  if (!dateStr) return null;
  return KOREAN_HOLIDAYS[dateStr] || null;
}

/**
 * 법정공휴일 여부 확인
 */
export function isHoliday(dateStr) {
  return !!getHoliday(dateStr);
}

/**
 * 주말(토/일) 또는 법정공휴일 여부 확인
 */
export function isWeekendOrHoliday(dateStr) {
  if (!dateStr) return false;
  if (isHoliday(dateStr)) return true;
  try {
    const d = new Date(dateStr + 'T00:00:00');
    const day = d.getDay();
    return day === 0 || day === 6; // 0: 일요일, 6: 토요일
  } catch (e) {
    return false;
  }
}
